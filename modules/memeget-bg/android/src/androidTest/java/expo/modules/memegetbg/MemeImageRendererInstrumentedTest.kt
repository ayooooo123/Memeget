  /** Blurring the source must still show the source, only softened. */
  @Test
  fun blursTheSourceBehindTheSubject() {
    val source = writeFixtureSource("render-fixture-bg-blur.png")
    val sharp = renderedFile(
      subjectPlan(
        widthPx = 320,
        heightPx = 200,
        sourceUri = source,
        layer = JSONObject().put("kind", "unavailable").put("id", "none")
          .put("layerKind", "subject").put("reason", "subject-mask-missing"),
        background = JSONObject()
          .put("mode", "source")
          .put("color", "#00000000")
          .put("assetUri", JSONObject.NULL)
          .put("blurScale", 0.0)
      )
    )
    val blurred = renderedFile(
      subjectPlan(
        widthPx = 320,
        heightPx = 200,
        sourceUri = source,
        layer = JSONObject().put("kind", "unavailable").put("id", "none")
          .put("layerKind", "subject").put("reason", "subject-mask-missing"),
        background = JSONObject()
          .put("mode", "blurred-source")
          .put("color", "#00000000")
          .put("assetUri", JSONObject.NULL)
          .put("blurScale", 0.8)
      )
    )
    try {
      val sharpBitmap = decode(sharp)
      val blurredBitmap = decode(blurred)
      try {
        // Quadrant centres keep their colours: this is still the photo.
        assertColorNear("blurred top-left", TOP_LEFT, blurredBitmap.getPixel(60, 40))
        assertColorNear("blurred bottom-right", BOTTOM_RIGHT, blurredBitmap.getPixel(260, 160))
        assertEquals("blurred background is opaque", 255, Color.alpha(blurredBitmap.getPixel(160, 100)))
        // The quadrant boundary is a hard edge sharp and a gradient blurred, so
        // neighbouring pixels across it differ far less once blurred.
        val sharpStep = channelDistance(
          sharpBitmap.getPixel(158, 100),
          sharpBitmap.getPixel(162, 100)
        )
        val blurredStep = channelDistance(
          blurredBitmap.getPixel(158, 100),
          blurredBitmap.getPixel(162, 100)
        )
        assertTrue(
          "blur softened the quadrant edge (sharp $sharpStep, blurred $blurredStep)",
          blurredStep < sharpStep / 2
        )
      } finally {
        sharpBitmap.recycle()
        blurredBitmap.recycle()
      }
    } finally {
      sharp.delete()
      blurred.delete()
      File(requireNotNull(source.path)).delete()
    }
  }

