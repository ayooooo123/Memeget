  /**
   * The memory question this task reopened: a cutout is a second RGBA bitmap
   * beside the output, and the sticker effects extract an alpha copy of it. A
   * full-frame cutout on a large export must stay inside the stated budget
   * rather than doubling the peak.
   */
  @Test
  fun keepsAFullFrameCutoutInsideABoundedFootprint() {
    val source = writeFixtureSource("render-fixture-cutout-memory.png")
    // 3000x2000 = 6 MP output (24 MB) with a cutout covering all of it.
    val cutout = writeCutoutFixture("cutout-memory.png", 1.5f)
    val planJson = subjectPlan(
      widthPx = 3000,
      heightPx = 2000,
      sourceUri = source,
      layer = subjectLayer(
        cutoutUri = Uri.fromFile(cutout).toString(),
        rect = JSONObject().put("x", 0.0).put("y", 0.0).put("width", 3000.0).put("height", 2000.0),
        outlineColor = "#FFFFFFFF",
        outlinePx = 24.0,
        shadowBlurPx = 18.0,
        shadowOffsetPx = 24.0
      )
    )
    var rendered: File? = null
    val peak = measuringPeakNativeHeap { rendered = renderedFile(planJson) }
    val output = requireNotNull(rendered)
    try {
      val bitmap = decode(output)
      try {
        assertEquals("full-frame cutout still fills the canvas", 3000, bitmap.width)
        assertEquals("cutout centre is opaque", 255, Color.alpha(bitmap.getPixel(1500, 1000)))
      } finally {
        bitmap.recycle()
      }
      // Output bitmap is 24 MB; the cutout decode is capped at a quarter of the
      // 16 MP plan budget (16 MB) and the alpha silhouette is a quarter of that.
      assertTrue(
        "peak native heap growth ${peak / (1024 * 1024)} MB must stay under 96 MB",
        peak < 96L * 1024 * 1024
      )
    } finally {
      output.delete()
      cutout.delete()
      File(requireNotNull(source.path)).delete()
    }
  }

