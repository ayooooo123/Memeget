  /**
   * A fully opaque cutout with the given aspect ratio and no transparent margin,
   * so the opaque pixels the renderer produces ARE the placement rectangle.
   */
  private fun writeCutoutFixture(name: String, aspect: Float): File {
    val height = 240
    val width = Math.max(1, Math.round(height * aspect))
    val bitmap = Bitmap.createBitmap(width, height, Bitmap.Config.ARGB_8888)
    bitmap.eraseColor(CUTOUT_COLOR)
    val file = File(context.cacheDir, name)
    FileOutputStream(file).use { stream ->
      assertTrue("cutout png encoded", bitmap.compress(Bitmap.CompressFormat.PNG, 100, stream))
    }
    bitmap.recycle()
    return file
  }

  private fun transparentBackground(): JSONObject = JSONObject()
    .put("mode", "transparent")
    .put("color", "#00000000")
    .put("assetUri", JSONObject.NULL)
    .put("blurScale", 0.0)

  /**
   * A minimal plan carrying exactly one subject layer. Hand-built rather than
   * read from an asset because the numbers come from the committed parity
   * fixture, which is itself pinned against the TypeScript builder — so the
   * geometry still originates on the other side of the bridge.
   */
  private fun subjectPlan(
    widthPx: Int,
    heightPx: Int,
    sourceUri: Uri,
    layer: JSONObject,
    background: JSONObject = transparentBackground()
  ): String = JSONObject()
    .put("version", MemeImageRenderer.PLAN_VERSION)
    .put("id", "cutout-test")
    .put("timeUs", 0)
    .put(
      "source",
      JSONObject()
        .put("uri", sourceUri.toString())
        .put("widthPx", 640)
