  /**
   * The parity gate Task 3.2 owes: a cutout has to land on the same FRACTION of
   * the canvas whether it is drawn onto a preview surface or a full-resolution
   * export. Placement comes from the committed fixture (generated by
   * resolveCutoutPlacement in TypeScript); the left-hand side of every
   * comparison is measured off the rendered pixels.
   */
  @Test
  fun placesACutoutOnTheSameFractionOfTheCanvasAtEveryScale() {
    val fixtures = readCutoutParityFixtures()
    assertEquals(
      "fixture version matches the renderer",
      MemeImageRenderer.PLAN_VERSION,
      fixtures.getInt("version")
    )
    val tolerance = fixtures.getDouble("tolerancePx")
    val canvases = fixtures.getJSONArray("canvases")
    val cases = fixtures.getJSONArray("cases")
    val source = writeFixtureSource("render-fixture-cutout-parity.png")
    var verified = 0
    try {
      for (caseIndex in 0 until cases.length()) {
        val parityCase = cases.getJSONObject(caseIndex)
        if (!parityCase.getBoolean("pixelVerifiable")) continue
        val id = parityCase.getString("id")
        val normalized = parityCase.getJSONObject("normalizedRect")
        val placements = parityCase.getJSONArray("placements")
        val first = placements.getJSONObject(0).getJSONObject("rect")
        val aspect = (first.getDouble("width") / first.getDouble("height")).toFloat()
        val cutout = writeCutoutFixture("cutout-parity-$id.png", aspect)
        try {
          for (placementIndex in 0 until placements.length()) {
            val placement = placements.getJSONObject(placementIndex)
            val canvas = canvases.getJSONObject(placement.getInt("canvas"))
            val widthPx = canvas.getInt("widthPx")
            val heightPx = canvas.getInt("heightPx")
            val rendered = renderedFile(
              subjectPlan(
                widthPx = widthPx,
                heightPx = heightPx,
                sourceUri = source,
                layer = subjectLayer(
                  cutoutUri = Uri.fromFile(cutout).toString(),
                  rect = placement.getJSONObject("rect"),
                  rotationDegrees = placement.getDouble("rotationDegrees"),
                  opacity = placement.getDouble("opacity")
                )
              )
            )
            try {
              assertPngSignature(rendered)
              val bitmap = decode(rendered)
              try {
                assertEquals("$id: output width", widthPx, bitmap.width)
                assertEquals("$id: output height", heightPx, bitmap.height)
                val bounds = requireNotNull(opaqueBounds(bitmap)) { "$id: nothing was drawn" }
                val expectedLeft = normalized.getDouble("x") * widthPx
                val expectedTop = normalized.getDouble("y") * heightPx
                val expectedWidth = normalized.getDouble("width") * widthPx
                val expectedHeight = normalized.getDouble("height") * heightPx
                assertNear("$id@${widthPx}x$heightPx left", expectedLeft, bounds.left.toDouble(), tolerance)
                assertNear("$id@${widthPx}x$heightPx top", expectedTop, bounds.top.toDouble(), tolerance)
                assertNear("$id@${widthPx}x$heightPx width", expectedWidth, bounds.width.toDouble(), tolerance)
                assertNear("$id@${widthPx}x$heightPx height", expectedHeight, bounds.height.toDouble(), tolerance)
                // The cutout's own colour has to survive compositing, and its
                // opacity has to be the one the plan asked for.
                val centre = bitmap.getPixel(
                  (bounds.left + bounds.right) / 2,
                  (bounds.top + bounds.bottom) / 2
                )
                assertColorNear("$id: cutout colour", CUTOUT_COLOR, centre or Color.BLACK)
                assertNear(
                  "$id: opacity",
                  placement.getDouble("opacity") * 255,
                  Color.alpha(centre).toDouble(),
                  4.0
                )
                verified += 1
              } finally {
                bitmap.recycle()
              }
            } finally {
              rendered.delete()
            }
          }
        } finally {
          cutout.delete()
        }
      }
      assertTrue("parity: verified $verified renders", verified >= 6)
    } finally {
      File(requireNotNull(source.path)).delete()
    }
  }

  /**
   * Alpha has to survive the cutout path, not just the empty-canvas path: a
   * transparent background plus a subject is the export that makes a cutout
   * worth having, and a PNG that quietly flattened it to black is the failure
   * nobody notices until it is pasted somewhere light.
