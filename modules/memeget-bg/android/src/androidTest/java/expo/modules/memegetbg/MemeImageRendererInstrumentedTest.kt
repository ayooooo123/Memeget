  private fun assertNear(message: String, expected: Double, actual: Double, tolerance: Double) {
    assertTrue(
      "$message: expected ${"%.2f".format(expected)} +/- $tolerance, got ${"%.2f".format(actual)}",
      Math.abs(expected - actual) <= tolerance
    )
  }

  private fun channelDistance(first: Int, second: Int): Int = maxOf(
    Math.abs(Color.red(first) - Color.red(second)),
    Math.abs(Color.green(first) - Color.green(second)),
    Math.abs(Color.blue(first) - Color.blue(second))
  )

