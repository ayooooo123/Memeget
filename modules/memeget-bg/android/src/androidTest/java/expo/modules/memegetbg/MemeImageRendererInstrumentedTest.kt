  private class OpaqueBounds(
    val left: Int,
    val top: Int,
    val right: Int,
    val bottom: Int
  ) {
    val width: Int get() = right - left
    val height: Int get() = bottom - top
    override fun toString(): String = "[$left,$top .. $right,$bottom]"
  }

  /**
   * Bounds of the pixels the renderer actually drew.
   *
   * Threshold 32 rather than 255: a half-opacity sticker draws at alpha 127 and
   * bilinear filtering leaves a one-pixel ramp at every edge, so counting only
   * fully opaque pixels would measure something narrower than what was drawn.
   */
  private fun opaqueBounds(bitmap: Bitmap): OpaqueBounds? {
    var left = bitmap.width
    var top = bitmap.height
    var right = -1
    var bottom = -1
    val row = IntArray(bitmap.width)
    for (y in 0 until bitmap.height) {
      bitmap.getPixels(row, 0, bitmap.width, 0, y, bitmap.width, 1)
      for (x in 0 until bitmap.width) {
        if (Color.alpha(row[x]) < 32) continue
        if (x < left) left = x
        if (x > right) right = x
        if (y < top) top = y
        if (y > bottom) bottom = y
      }
    }
    if (right < left || bottom < top) return null
    return OpaqueBounds(left, top, right + 1, bottom + 1)
  }

